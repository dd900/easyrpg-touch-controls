#!/usr/bin/env node
// Builds index.html and the files in variants/ from src/index.template.html.
//
//   node build.js          write the files
//   node build.js --check  exit with an error if a file is out of date
//
// Template directives sit on their own line, as an HTML, CSS or JS comment:
//   <!-- @if expr -->   /* @if expr */   // @if expr   (also @elif, @else, @endif)
// An expression combines the flags below with !, && and || (no parentheses).
// {{name}} placeholders are replaced with the values in `tokens`.

const fs = require('fs');
const path = require('path');

const TEMPLATE = path.join(__dirname, 'src', 'index.template.html');
const NOTICE = '<!-- Generated by build.js from src/index.template.html; changes made here are lost when it is rebuilt. -->';

const OUTPUTS = {
  'index.html': { joystick: true, dpad: true, numpad: true },
  'variants/index.dpad.html': { joystick: false, dpad: true, numpad: true },
  'variants/index.joystick.html': { joystick: true, dpad: false, numpad: true },
  'variants/index.dpad-no-numpad.html': { joystick: false, dpad: true, numpad: false },
  'variants/index.joystick-no-numpad.html': { joystick: true, dpad: false, numpad: false }
};

const DIRECTIVE = /^\s*(?:<!--|\/\*|\/\/)\s*@(if|elif|else|endif)\b(.*?)\s*(?:-->|\*\/)?\s*$/;

function render(source, features) {
  // The toggle only exists when both directional controls are present.
  const flags = { ...features, toggle: features.joystick && features.dpad };
  const tokens = {
    shortcutButtons: flags.toggle ? 5 : 4,
    numpadSelector: flags.numpad ? ', #numpad-wrap' : '',
    toggleSelector: flags.toggle ? ', #dpad-mode-toggle' : ''
  };

  const evaluate = expression => expression.split('||').some(group =>
    group.split('&&').every(term => {
      const negated = term.trim().startsWith('!');
      const name = term.trim().replace(/^!/, '').trim();
      if (!(name in flags)) throw new Error(`unknown flag "${name}"`);
      return negated ? !flags[name] : flags[name];
    }));

  const fill = line => line.replace(/\{\{(\w+)\}\}/g, (_, name) => {
    if (!(name in tokens)) throw new Error(`unknown placeholder "${name}"`);
    return tokens[name];
  });

  const eol = source.includes('\r\n') ? '\r\n' : '\n';
  const lines = [];
  const stack = [];

  source.split(/\r?\n/).forEach((line, index) => {
    try {
      const match = line.match(DIRECTIVE);
      if (!match) {
        if (stack.every(block => block.active)) lines.push(fill(line));
        return;
      }

      const [, kind, expression] = match;
      if (kind === 'if') {
        const parentActive = stack.every(block => block.active);
        const condition = evaluate(expression);
        stack.push({ parentActive, active: parentActive && condition, taken: condition });
        return;
      }

      const block = stack[stack.length - 1];
      if (!block) throw new Error(`@${kind} without @if`);
      if (kind === 'endif') {
        stack.pop();
        return;
      }

      const condition = kind === 'else' || evaluate(expression);
      block.active = block.parentActive && !block.taken && condition;
      block.taken = block.taken || condition;
    } catch (error) {
      throw new Error(`${path.relative(__dirname, TEMPLATE)}:${index + 1}: ${error.message}`);
    }
  });

  if (stack.length) throw new Error(`${path.relative(__dirname, TEMPLATE)}: unclosed @if`);
  lines.splice(1, 0, NOTICE); // right after the doctype
  return lines.join(eol);
}

const source = fs.readFileSync(TEMPLATE, 'utf8');
const check = process.argv.includes('--check');
let outOfDate = 0;

for (const [file, features] of Object.entries(OUTPUTS)) {
  const target = path.join(__dirname, file);
  const output = render(source, features);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;

  if (current === output) continue;
  if (check) {
    console.error(`Out of date: ${file}`);
    outOfDate++;
    continue;
  }

  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
  console.log(`Wrote ${file}`);
}

if (check) {
  if (outOfDate) process.exit(1);
  console.log('All files are up to date.');
}
